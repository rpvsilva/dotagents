#!/usr/bin/env python3
"""Ships one ticket's PR into the base branch: build-epic step 7.

Usage: python3 -I ship_ticket.py <run> <TT> open
       python3 -I ship_ticket.py <run> <TT> merge [--reviewed <sha>]

The base a new PR opens against is `decisions.md`'s `base:` line when it names a branch, else the run's default branch.

`open` pushes the ticket branch (its local tip, where its tasks merged; `push` on a refusal), puts the ticket's worktree
`<run>/worktrees/TT` at that tip, detached, so a later task merge can move the branch, then opens the ticket PR with
the ticket's title and body, generated by `steplib/prbody.py` from the run folder alone (kept in
`<run>/logs/TT-pr-body.md`): every section of the repo's PR template filled from the ticket, its tasks, `decisions.md`
and `reports/*.checks.json`, then the tasks with their merge commits and acceptance criteria and `Closes #n`. It takes no
prose. When the repo has a template and the run cannot
fill a section of it (a heading it does not know, or `Testing` with no saved suite results), it fails
`empty-template-section <sections>` and sends nothing. Otherwise it edits the ticket's `PR:` (or the open PR from the
ticket branch: a rerun), or opens one and records it as the ticket's `PR:` line. Prints `OK TT open pr=<n>`.

`merge` reads the PR's real base (`baseRefName`). Into the default branch with the `merge_command` Setting unset, a
repo with a `.review-gate.yml` fails `no-merge-rule`: a bare `gh pr merge` would land around the repo's gate. Otherwise
it pushes the local ticket branch (a no-op unless a merge since `open` was not pushed) and merges the ticket PR at
the ticket branch's tip on origin by the merge rule, then sets the ticket `merged`, removes
its worktree and local branch, and, when the PR's base is the default branch, closes the ticket's issues (into any other
base they stay open). When the `merge_command` rule refuses for want of a human approval (its own output names an
approval, a required review or a code owner), it sets the ticket `in-review` and removes the worktree instead.

A PR whose base is not the run's base fails `wrong-base <branch>` before anything else, so nothing is pushed. Then,
whatever the base, the merge guard (`steplib/guard.py`, the format in `../merge-guard.md`) checks
`origin/<base>...<ticket head>` against the rules on `origin/<default branch>`: a hit whose rule `decisions.md` does not waive
`yes` fails `guarded <file:line rule>; ...` before `no-merge-rule`, the Checks or any push.

Into any other base than the default branch, which the repo's gate does not judge, it first runs `map.md`'s Checks on
the ticket head in a scratch worktree (`red <suite>` stops it), and merges only when the ticket's tree is the reviewed
tree (`tree-mismatch`); either refusal merges and pushes nothing. Tasks land as merge commits, so the ticket branch
keeps every base merge a hub task made. The reviewed head is the commit the ticket PR's review was posted on
(`<run>/logs/PR<n>-review.json`), else `--reviewed <sha>`, which overrides it, else it fails `no-review`; one git does
not know fails `reviewed-unknown`. A ticket merged into such a base labels its issues `merged-to-<base>`.

Prints `OK TT merged pr=<n>` or `OK TT in-review pr=<n>`, or `FAIL TT <reason> (log: ...)`: `wrong-base <branch>` (a PR
into anything but the run's base), `red <suite>`, `merge`, `head-moved`,
`no-pr`, `no-merge-rule`, `no-review`, `reviewed-unknown`, `tree-mismatch`, `pr-view`,
`push`, `pr-edit`, `pr-create`, `empty-template-section <sections>`, `guarded <file:line rule>; ...` (a hit not
waived), `guard-no-base: <ref>` (no `origin/<base>` or `origin/<default branch>`), `guard-bad-range: <range>`, `bad-rule: <line>` (an unreadable
guard rule) and `git-<cmd>` (a git command of the guard failed).
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from steplib import checks, ci, core, gh, gitops, guard, merge, prbody, runfolder, tracker  # noqa: E402

USAGE = "ship_ticket.py <run> <TT> open | merge [--reviewed <sha>]"
GATE = ".review-gate.yml"
URL = re.compile(r"https?://\S+/pull/(\d+)")
WAITS_ON_HUMAN = re.compile(r"approv|review required|required review|code ?owner", re.IGNORECASE)


class Ship:
    def __init__(self, ctx):
        self.ctx, self.run = ctx, ctx.run_dir
        info = runfolder.run_info(self.run)
        self.repo, self.default = core.resolve(info["Repo"]), info["Default"]
        self.base = ci.base(self.run, self.default)
        self.ticket = runfolder.ticket_file(self.run, ctx.id)
        self.branch = runfolder.get(self.ticket, "Branch")
        if not self.branch:
            raise core.Fail("ticket-no-branch")
        self.worktree = self.run / "worktrees" / ctx.id
        self.git = gitops.Git(self.repo, ctx.log)

    def gh(self, args, what):
        res = gh.gh(args, self.ctx.log, cwd=self.repo)
        if res.rc != 0:
            raise core.Fail(what)
        return res

    def find_open(self):
        """(number, url) of the open PR from the ticket branch into the base, or None."""
        res = self.gh(["pr", "list", "--head", self.branch, "--base", self.base, "--state", "open",
                       "--json", "number,url"], "pr-list")
        try:
            prs = json.loads(res.out or "[]")
        except ValueError:
            raise core.Fail("pr-list")
        return (str(prs[0]["number"]), prs[0].get("url") or f"#{prs[0]['number']}") if prs else None

    def push(self):
        """Pushes the local ticket branch, where its tasks merged, to origin; returns its tip."""
        self.git.fetch()
        tip = self.git.ticket_tip(self.branch)
        if self.git.push("origin", f"refs/heads/{self.branch}:refs/heads/{self.branch}").rc != 0:
            raise core.Fail("push")
        return tip

    def open(self):
        tip = self.push()
        if not self.worktree.is_dir():
            self.git.worktree_add(self.worktree, ref=tip, detach=True)
        else:  # a rerun after a fix landed on the ticket branch reads the fix, not the old head
            self.git._git("checkout", "-q", "--detach", tip, cwd=self.worktree)
        template = prbody.template(self.worktree)
        body = prbody.ticket_body(self.run, self.ticket, template=template)
        body_file = self.run / "logs" / f"{self.ctx.id}-pr-body.md"
        body_file.write_text(body, encoding="utf-8")
        empty = prbody.empty_sections(template, body) if template is not None else []
        if empty:
            self.ctx.note(f"the PR template's sections left empty: {', '.join(empty)}; body in {body_file}")
            raise core.Fail(f"empty-template-section {', '.join(empty)}")
        title = ci.title(self.ticket)
        line = runfolder.get(self.ticket, "PR")
        found = (ci.pr_number(line), line) if ci.pr_number(line) else self.find_open()
        if found:
            number, url = found
            self.gh(["pr", "edit", number, "--title", title, "--body-file", body_file], "pr-edit")
        else:
            res = self.gh(["pr", "create", "--base", self.base, "--head", self.branch, "--title", title,
                           "--body-file", body_file], "pr-create")
            m = URL.search(res.out)
            if not m:
                raise core.Fail("pr-create")
            number, url = m.group(1), m.group(0)
        if not line:
            runfolder.set_header(self.ticket, "PR", url)
        return "open", f"pr={number}"

    def gated(self):
        """True when the repo has a `.review-gate.yml`, on the default branch's tip on origin or in its checkout."""
        res = self.git._git("cat-file", "-e", f"origin/{self.default}:{GATE}", check=False)
        return res.rc == 0 or (self.repo / GATE).is_file()

    def finish(self):
        """Removes the ticket's worktree and its local branch."""
        self.git.worktree_remove(self.worktree)
        self.git.branch_delete(self.branch)

    def reviewed(self, number, given):
        """The reviewed head: `given`, else the commit the PR's posted review was on."""
        if given:
            return given
        path = self.run / "logs" / f"PR{number}-review.json"
        try:
            commit = json.loads(path.read_text(encoding="utf-8")).get("commit_id") if path.is_file() else None
        except (ValueError, AttributeError):
            commit = None
        if not commit:
            self.ctx.note(f"no reviewed head: pass --reviewed <sha>, or post the ticket's review ({path} is missing)")
            raise core.Fail("no-review")
        return commit

    def check_reviewed(self, reviewed, sha):
        """Fails `reviewed-unknown` when git does not know the reviewed head, and `tree-mismatch` when the ticket's tree
        is not the reviewed one (a merge landed after the review)."""
        try:
            reviewed = self.git.tip(reviewed)
        except core.Fail:
            raise core.Fail("reviewed-unknown")
        if self.git.tree(sha) != self.git.tree(reviewed):
            self.ctx.note(f"the ticket head {sha} is not the reviewed tree of {reviewed}: review its head again")
            raise core.Fail("tree-mismatch")

    def run_checks(self, sha):
        """Runs `map.md`'s Checks on `sha` in a scratch worktree: the proof a PR into a non-default base merges on, since
        the repo's gate judges only PRs into the default branch. Fails `red <suite>`."""
        scratch = self.run / "worktrees" / f"{self.ctx.id}-checks"
        self.git.worktree_remove(scratch)
        self.git.worktree_add(scratch, ref=sha, detach=True)
        try:
            suites = checks.run_all(checks.commands(self.run / "map.md"), scratch, self.ctx.log, self.run)
        finally:
            self.git.worktree_remove(scratch)
        if suites[-1].rc != 0:
            raise core.Fail(f"red {suites[-1].command}")

    def merge(self, reviewed=None):
        """Merges the ticket's PR."""
        line = runfolder.get(self.ticket, "PR")
        number = ci.pr_number(line)
        if not number:
            raise core.Fail("no-pr")
        command = merge.setting(self.repo, "merge_command", self.ctx.log)
        self.git.fetch()
        sha = self.git.ticket_tip(self.branch)
        into = merge.view(number, self.ctx.log, self.repo).get("baseRefName")
        if not into:
            raise core.Fail("pr-view")
        merge.check_base(number, into, self.base, self.ctx.log)  # before anything is pushed
        guard.check(self.repo, f"origin/{self.base}...{sha}", self.run, self.ctx.log)
        if not command and into == self.default and self.gated():
            self.ctx.note(f"{GATE} gates {into}, and the merge_command Setting is unset: set it to the repo's merge rule")
            raise core.Fail("no-merge-rule")
        if into != self.default:
            self.run_checks(sha)
            self.check_reviewed(self.reviewed(number, reviewed), sha)
        self.push()
        try:
            merge.merge(number, sha, self.repo, self.ctx.log, self.base, command)
        except core.Fail as e:
            # Only the repo's own rule answers "waits on a human"; a bare gh merge's refusal is a failure.
            if not command or e.reason != "merge" or not WAITS_ON_HUMAN.search(getattr(e, "said", "")):
                raise
            runfolder.set_header(self.ticket, "Status", "in-review")
            self.finish()
            return "in-review", f"pr={number}"
        runfolder.set_header(self.ticket, "Status", "merged")
        self.finish()
        issues = tracker.Tracker(self.run, self.repo, self.ctx.log)
        for n in prbody.issues(self.ticket):
            if into == self.default:
                issues.close(n, f"Shipped in {line}.")
            else:
                issues.add_label(n, f"merged-to-{into}")
        return "merged", f"pr={number}"


def step(ctx):
    args = list(ctx.args)
    if args == ["open"]:
        return Ship(ctx).open()
    if args[:1] == ["merge"] and len(args) in (1, 3) and (len(args) == 1 or args[1] == "--reviewed"):
        return Ship(ctx).merge(args[2] if len(args) == 3 else None)
    raise core.Fail(f"usage: {USAGE}")


if __name__ == "__main__":
    core.main("ship_ticket", step, usage="open | merge [--reviewed <sha>]")
